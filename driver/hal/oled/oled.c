void oled_show_string(uint8_t x, uint8_t y, const char *str) {
  uint8_t cx = x;
  oled_write_cmd(0xB0 + y);
  oled_write_cmd((cx & 0x0F) + 0x00);
  oled_write_cmd(0x10 | (cx >> 4));

  while (*str) {
    uint8_t c = *str++;
    if (c < 32 || c > 127)
      c = ' ';
    uint8_t idx = c - 32;
    for (uint8_t i = 0; i < 6; i++)
      oled_write_data(font_6x8[idx][i]);
    cx += 6;
    if (cx >= 126)
      break;
  }

  while (cx < 128) {
    for (uint8_t i = 0; i < 6 && cx < 128; i++, cx++)
      oled_write_data(0);
  }
}

void oled_printf(uint8_t x, uint8_t y, const char *fmt, ...) {
  char buf[32];
  va_list args;
  va_start(args, fmt);
  vsnprintf(buf, sizeof(buf), fmt, args);
  va_end(args);
  oled_show_string(x, y, buf);
}
