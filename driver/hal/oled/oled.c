/* ===================================================
 * Software I2C bit-bang
 * =================================================== */
#define SCL_H()  HAL_GPIO_WritePin(HW_OLED_SCL_PORT, HW_OLED_SCL_PIN, GPIO_PIN_SET)
#define SCL_L()  HAL_GPIO_WritePin(HW_OLED_SCL_PORT, HW_OLED_SCL_PIN, GPIO_PIN_RESET)
#define SDA_H()  HAL_GPIO_WritePin(HW_OLED_SDA_PORT, HW_OLED_SDA_PIN, GPIO_PIN_SET)
#define SDA_L()  HAL_GPIO_WritePin(HW_OLED_SDA_PORT, HW_OLED_SDA_PIN, GPIO_PIN_RESET)
#define SDA_IN() HAL_GPIO_ReadPin(HW_OLED_SDA_PORT, HW_OLED_SDA_PIN)

static void i2c_delay(void) { for (volatile int i = 0; i < 20; i++); }

static void i2c_start(void) {
  SDA_H(); SCL_H(); i2c_delay();
  SDA_L(); i2c_delay(); SCL_L();
}

static void i2c_stop(void) {
  SDA_L(); SCL_H(); i2c_delay();
  SDA_H(); i2c_delay();
}

static uint8_t i2c_write(uint8_t dat) {
  for (uint8_t i = 0; i < 8; i++) {
    if (dat & 0x80) SDA_H(); else SDA_L();
    dat <<= 1;
    SCL_H(); i2c_delay(); SCL_L();
  }
  SDA_H(); SCL_H(); i2c_delay();
  uint8_t ack = SDA_IN();
  SCL_L();
  return ack;
}

/* ===================================================
 * OLED command / data
 * =================================================== */
static void oled_write_cmd(uint8_t cmd) {
  i2c_start();
  i2c_write(HW_OLED_ADDR);
  i2c_write(0x00);
  i2c_write(cmd);
  i2c_stop();
}

static void oled_write_data(uint8_t dat) {
  i2c_start();
  i2c_write(HW_OLED_ADDR);
  i2c_write(0x40);
  i2c_write(dat);
  i2c_stop();
}

/* ===================================================
 * Init + clear
 * =================================================== */
void oled_init(void) {
  HAL_Delay(100);
  oled_write_cmd(0xAE);
  oled_write_cmd(0x20); oled_write_cmd(0x00);
  oled_write_cmd(0xB0);
  oled_write_cmd(0xC8);
  oled_write_cmd(0x00); oled_write_cmd(0x10);
  oled_write_cmd(0x40);
  oled_write_cmd(0x81); oled_write_cmd(0xFF);
  oled_write_cmd(0xA1);
  oled_write_cmd(0xA6);
  oled_write_cmd(0xA8); oled_write_cmd(0x3F);
  oled_write_cmd(0xA4);
  oled_write_cmd(0xD3); oled_write_cmd(0x00);
  oled_write_cmd(0xD5); oled_write_cmd(0xF0);
  oled_write_cmd(0xD9); oled_write_cmd(0x22);
  oled_write_cmd(0xDA); oled_write_cmd(0x12);
  oled_write_cmd(0xDB); oled_write_cmd(0x20);
  oled_write_cmd(0x8D); oled_write_cmd(0x14);
  oled_write_cmd(0xAF);
  oled_clear();
}

void oled_clear(void) {
  for (uint8_t p = 0; p < 8; p++) {
    oled_write_cmd(0xB0 + p);
    oled_write_cmd(0x00);
    oled_write_cmd(0x10);
    for (uint8_t c = 0; c < 128; c++)
      oled_write_data(0);
  }
}

